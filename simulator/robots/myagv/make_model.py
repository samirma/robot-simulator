#!/usr/bin/env python
"""Generate model.xml for the Elephant Robotics myAGV Pi 2023.

The upstream model (elephantrobotics/myagv_ros, branch myagv_ros_2023Pi,
myagv_urdf/urdf/) is **visualisation only**: two links joined by a dummy `continuous`
joint, three COLLADA meshes, and no wheels, collision geometry, inertia or scale that
MuJoCo can use. So the MJCF is authored here rather than converted, reusing only the
meshes for appearance.

What this script does:

1. **Converts the COLLADA meshes to OBJ** (MuJoCo reads OBJ/STL, not DAE) and
   **derives the scale from the published dimensions** rather than trusting the file:
   the meshes are in arbitrary units ~12.3 x 9.0 x 5.2, and the real chassis is
   311.15 x 230 x 110 mm, so the scale is fixed by matching the footprint. The mesh is
   re-centred on its footprint with z=0 at the wheel contact plane.

2. **Emits a holonomic planar base** — slide-X / slide-Y / hinge-Z virtual joints with
   position actuators, named to match `HoloJointsRobotBaseGroup`
   (`molmo_spaces/robots/robot_views/abstract.py`), which is what MolmoSpaces already
   uses for RB-Y1. Mecanum wheels are *not* simulated as rolling contacts: four-roller
   contact is fragile and buys nothing, and a holonomic planar base reproduces exactly
   the motion envelope a Mecanum drive has. The wheels stay as visual geometry.

3. **Adds a forward-facing `front_camera`** on the top plate at roughly RealSense D435
   framing, which is the feed the robot_console teleop tool displays.

Run:  python robots/myagv/make_model.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import trimesh

HERE = Path(__file__).resolve().parent
UPSTREAM = HERE / "urdf"
ASSETS = HERE / "assets"
OUT = HERE / "model.xml"

# Published myAGV 2023 Pi specs (elephantrobotics.com/en/myagv-2023-pi-specifications-en/)
CHASSIS_L = 0.31115  # m, along +x (forward)
CHASSIS_W = 0.230  # m, along +y
NET_WEIGHT = 4.16  # kg

# Keep the collision box just clear of the floor. The base has no vertical DoF, so it
# cannot fall; lifting the box a few mm stops it scraping the floor and fighting the
# actuators, while still colliding with walls and furniture.
GROUND_CLEARANCE = 0.005


def convert_meshes() -> dict:
    """Convert the DAE meshes to OBJ at true scale, re-centred. Returns key dimensions."""
    ASSETS.mkdir(exist_ok=True)

    base = trimesh.load(UPSTREAM / "myagv_base.dae", force="mesh")
    up = trimesh.load(UPSTREAM / "myagv_up.dae", force="mesh")

    # Scale is derived from the footprint: x and y independently imply 0.02522 and
    # 0.02551, so take the mean rather than distorting the model with a non-uniform fit.
    raw = base.extents
    scale = float(np.mean([CHASSIS_L / raw[0], CHASSIS_W / raw[1]]))

    # Re-centre on the footprint of the *base* mesh, with z=0 at the wheel contact
    # plane, and apply the same transform to both meshes so they stay aligned.
    lo, hi = base.bounds
    centre = np.array([(lo[0] + hi[0]) / 2, (lo[1] + hi[1]) / 2, lo[2]])

    dims = {}
    for name, mesh in (("myagv_base", base), ("myagv_up", up)):
        mesh.apply_translation(-centre)
        mesh.apply_scale(scale)
        mesh.export(ASSETS / f"{name}.obj")
        dims[name] = {"bounds": mesh.bounds.copy(), "extents": mesh.extents.copy()}
        print(f"  {name}.obj  extents={np.round(mesh.extents, 4)}")

    total_h = float(dims["myagv_up"]["bounds"][1][2])
    deck_h = float(dims["myagv_base"]["bounds"][1][2])
    print(f"  scale={scale:.6f}  deck height={deck_h:.4f} m  total height={total_h:.4f} m")

    return {"scale": scale, "deck_h": deck_h, "total_h": total_h}


TEMPLATE = """<mujoco model="myagv">
<!--
  GENERATED by make_model.py - do not edit by hand.

  Meshes derive from elephantrobotics/myagv_ros (branch myagv_ros_2023Pi), converted
  from COLLADA and scaled to the published 311.15 x 230 x 110 mm chassis.
  The drive is an idealised holonomic planar base, not simulated Mecanum wheels;
  see make_model.py.
-->
  <compiler angle="radian" meshdir="assets" autolimits="true"/>

  <!-- Applies when this model is loaded standalone. When the robot is attached into a
       house, only the body subtree is grafted in and the scene's own option wins. -->
  <option integrator="implicitfast" timestep="0.002"/>

  <default>
    <default class="myagv">
      <default class="visual">
        <geom type="mesh" contype="0" conaffinity="0" group="2"/>
      </default>
      <default class="collision">
        <geom group="3" condim="3" friction="0.6 0.005 0.0001"/>
      </default>
      <!-- Gains for a {mass} kg chassis. `dampratio` is used rather than an explicit
           kv: MuJoCo derives the damping from the *actual* effective inertia, which
           matters a lot here because the yaw inertia is only ~0.05 kg m^2. A hand-set
           kv large enough to look critically damped violates the explicit-integration
           stability bound (kv*dt/I < 2) and blows the sim up. -->
      <default class="drive">
        <position kp="2000" dampratio="1"/>
      </default>
      <default class="turn">
        <position kp="120" dampratio="1"/>
      </default>
    </default>
  </default>

  <asset>
    <mesh name="myagv_base" file="myagv_base.obj"/>
    <mesh name="myagv_up" file="myagv_up.obj"/>
    <material name="myagv_body" rgba="0.16 0.17 0.20 1"/>
    <material name="myagv_deck" rgba="0.85 0.86 0.88 1"/>
  </asset>

  <worldbody>
    <body name="base" childclass="myagv">
      <!-- Virtual holonomic joints, world-aligned. Order (x, y, theta) is required by
           HoloJointsRobotBaseGroup. The robot must be inserted at the origin with
           identity rotation; placement is done by setting these joints. -->
      <!-- Only light joint damping; the actuators' dampratio does the real work, and
           stacking both would over-damp the yaw axis into instability. -->
      <joint name="base_x" type="slide" axis="1 0 0" limited="false" damping="5"/>
      <joint name="base_y" type="slide" axis="0 1 0" limited="false" damping="5"/>
      <joint name="base_theta" type="hinge" axis="0 0 1" limited="false" damping="0.5"/>

      <inertial pos="0 0 {com_z:.4f}" mass="{mass}"
        diaginertia="{ixx:.5f} {iyy:.5f} {izz:.5f}"/>

      <site name="base_site" pos="0 0 0" size="0.01" group="3"/>

      <geom class="visual" mesh="myagv_base" material="myagv_body"/>
      <geom class="visual" mesh="myagv_up" material="myagv_deck"/>

      <!-- Single box hull for the chassis: cheap, and the shape is close enough that
           the visual mesh is not visibly interpenetrating walls. -->
      <geom name="chassis" class="collision" type="box"
        size="{half_l:.4f} {half_w:.4f} {half_h:.4f}"
        pos="0 0 {box_z:.4f}"/>

      <!-- Mount point for a myCobot 280-class arm (not fitted). -->
      <site name="arm_mount" pos="0 0 {deck_h:.4f}" size="0.01" group="3"/>

      <!-- Forward-facing (+x) camera on the top deck, ~D435 framing. MuJoCo cameras
           look along -z with +y up, so xyaxes maps -z_cam onto +x_world. -->
      <camera name="front_camera" mode="fixed"
        pos="{cam_x:.4f} 0 {cam_z:.4f}" xyaxes="0 -1 0 0 0 1" fovy="42"/>
    </body>
  </worldbody>

  <actuator>
    <position class="drive" name="base_x_act" joint="base_x" ctrlrange="-25 25"/>
    <position class="drive" name="base_y_act" joint="base_y" ctrlrange="-25 25"/>
    <position class="turn" name="base_theta_act" joint="base_theta" ctrlrange="-100 100"/>
  </actuator>
</mujoco>
"""


def main() -> int:
    print("converting meshes...")
    dims = convert_meshes()

    deck_h = dims["deck_h"]
    total_h = dims["total_h"]

    half_l, half_w = CHASSIS_L / 2, CHASSIS_W / 2
    box_bottom = GROUND_CLEARANCE
    box_top = total_h
    half_h = (box_top - box_bottom) / 2
    box_z = box_bottom + half_h
    com_z = total_h * 0.4  # battery and motors sit low

    # Solid-box inertia about the centre of mass, a reasonable stand-in given the
    # upstream model carries no inertial data at all.
    m = NET_WEIGHT
    ixx = m * (CHASSIS_W**2 + total_h**2) / 12
    iyy = m * (CHASSIS_L**2 + total_h**2) / 12
    izz = m * (CHASSIS_L**2 + CHASSIS_W**2) / 12

    xml = TEMPLATE.format(
        mass=NET_WEIGHT,
        com_z=com_z,
        ixx=ixx,
        iyy=iyy,
        izz=izz,
        half_l=half_l,
        half_w=half_w,
        half_h=half_h,
        box_z=box_z,
        deck_h=deck_h,
        cam_x=half_l - 0.02,
        cam_z=total_h + 0.01,
    )
    OUT.write_text(xml)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
