"""The AiNex's vendor files are still the vendor's files.

    python shared/tests/ainex_provenance_check.py
    python shared/tests/ainex_provenance_check.py --update   # after a vendor pull

Stdlib only and no MuJoCo, so it runs under any interpreter and under either engine's
venv. `PROVENANCE.md` names the upstream commit in prose; this is what makes that a claim
the repo can check rather than one it merely states. The AiNex is the robot where it
matters most: its description is the only hardware source here under no stated licence, so
"verbatim" is the whole basis on which it is vendored, and an edit -- a re-export from
SolidWorks, a mesh nudged to fix something -- would otherwise be indistinguishable from
the vendor's own file for ever after.

Git blob hashes, not plain sha256, so a reading of this file can be checked against
`git hash-object <path>` or against GitHub's own blob ids without any tooling. The hash is
sha1 over `blob <bytes>\\0` followed by the content, which is the whole of git's object
format for a file -- no git binary needed here, and none in the check.

`ainex.urdf` is **generated** (`flatten_xacro.py` expands the xacro) and is listed for
completeness, flagged as such: it changes legitimately whenever the xacro does, and the
thing to re-run then is the flattener, not this table.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

URDF_DIR = Path(__file__).resolve().parents[1] / "robots" / "ainex" / "urdf"
PROVENANCE = URDF_DIR / "PROVENANCE.md"
#: The line format in PROVENANCE.md's hash table: `| <path> | <sha1> | <note> |`.
ROW = re.compile(r"^\|\s*`([^`]+)`\s*\|\s*`([0-9a-f]{40})`\s*\|\s*([^|]*?)\s*\|\s*$")


def blob_sha1(path: Path) -> str:
    """Git's own object id for a file's contents."""
    data = path.read_bytes()
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def vendor_files() -> list[Path]:
    """Everything vendored, in a stable order: the xacro sources, the README, the meshes.

    `ainex.urdf` is included even though it is generated -- it is what MuJoCo actually
    loads, so an edit to it is exactly as consequential as an edit to a mesh.
    """
    named = [
        URDF_DIR / "ainex.urdf.xacro",
        URDF_DIR / "materials.xacro",
        URDF_DIR / "transmissions.xacro",
        URDF_DIR / "UPSTREAM_README.md",
        URDF_DIR / "ainex.urdf",
    ]
    return named + sorted((URDF_DIR / "meshes").glob("*.STL"))


def recorded() -> dict[str, str]:
    """`{relative path: sha1}` as PROVENANCE.md records it."""
    out: dict[str, str] = {}
    for line in PROVENANCE.read_text().splitlines():
        match = ROW.match(line)
        if match:
            out[match.group(1)] = match.group(2)
    return out


def table(files: list[Path]) -> str:
    """The markdown table to paste into PROVENANCE.md."""
    rows = ["| File | git blob sha1 | |", "|---|---|---|"]
    for path in files:
        note = "generated by `flatten_xacro.py`" if path.name == "ainex.urdf" else "vendor"
        rows.append(f"| `{path.relative_to(URDF_DIR)}` | `{blob_sha1(path)}` | {note} |")
    return "\n".join(rows)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--update", action="store_true",
                    help="print the table to paste into PROVENANCE.md and exit")
    args = ap.parse_args()

    files = vendor_files()
    if args.update:
        print(table(files))
        return 0

    known = recorded()
    if not known:
        print(f"FAILED: {PROVENANCE.name} records no hashes; run with --update")
        return 1

    failures = 0
    for path in files:
        name = str(path.relative_to(URDF_DIR))
        actual = blob_sha1(path)
        expected = known.pop(name, None)
        if expected is None:
            print(f"  FAIL {name} - vendored but not recorded in {PROVENANCE.name}")
            failures += 1
        elif expected != actual:
            print(f"  FAIL {name} - recorded {expected[:12]}, found {actual[:12]}")
            failures += 1
    for name in known:
        print(f"  FAIL {name} - recorded but not present")
        failures += 1

    if failures:
        print(f"FAILED: {failures} vendor file(s) differ from what PROVENANCE.md records.\n"
              "If this followed a deliberate vendor pull, re-run with --update and check\n"
              "the figures in PROVENANCE.md's verification table again.")
        return 1
    print(f"all {len(files)} vendor files match PROVENANCE.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
